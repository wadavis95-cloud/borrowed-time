// Run whenever shipped model/music/thumbnail bytes change; freshness is tested.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {ALL_AVATAR_IDS} from '../src/avatars.js';
import {MAP_IDS} from '../src/maps.js';
const paths=[...ALL_AVATAR_IDS.map(id=>`/assets/characters/${id}.glb`),...MAP_IDS.flatMap(id=>[`/assets/maps/${id}.svg`,`/assets/music/${id}.mp3`])].sort();
const versions={};for(const path of paths)versions[path]=createHash('sha256').update(await readFile(new URL('..'+path,import.meta.url))).digest('hex');
await writeFile(new URL('../src/asset-versions.js',import.meta.url),'// Generated by npm run build:asset-versions. Do not hand-edit.\nexport const ASSET_VERSIONS=Object.freeze('+JSON.stringify(versions,null,2)+');\nexport function assetUrl(path){return ASSET_VERSIONS[path]?`${path}?v=${ASSET_VERSIONS[path]}`:path;}\n');
console.log(`Versioned ${paths.length} immutable assets.`);
